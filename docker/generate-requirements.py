#!/usr/bin/env python3
"""Regenerate the container requirements files from uv.lock and the hand pins.

Run from the repository root:

    uv run python docker/generate-requirements.py

Three files come out, each installed by the Dockerfile with `--require-hashes`:

- `requirements-container.txt`: the MKL runtime closure and the runtime pins.
  The runtime section is derived from `uv.lock`, hashes included, so it cannot
  drift from the resolution the test suite runs against.
- `requirements-numpy-mkl.txt`: the ILP64 NumPy wheel and `mkl-service`, which
  come from the custom ILP64 index rather than PyPI.
- `requirements-build.txt`: the build backend and its dependencies, exported
  from the `docker-build` dependency group in `uv.lock`. The image builds this
  checkout without isolation, so these are the only build-time packages.

The MKL and ILP64 pins are not in `uv.lock` at all: JAMMA never imports them
directly, so they are declared here with the sha256 of their linux x86_64
wheel. When bumping one, take the hash from the index that serves it: PyPI's
JSON API (`https://pypi.org/pypi/<name>/<version>/json`) for the MKL closure,
and the `#sha256=` fragment on the ILP64 index page for the other two.

`uv export` emits a universal resolution: Windows-only packages carry markers,
and `numpy` forks across the 3.11/3.12 boundary. The image is linux/amd64 on
CPython 3.12, and its `numpy` comes from the ILP64 index rather than PyPI, so
both get filtered out here.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTAINER_TARGET = ROOT / "docker" / "requirements-container.txt"
NUMPY_MKL_TARGET = ROOT / "docker" / "requirements-numpy-mkl.txt"
BUILD_TARGET = ROOT / "docker" / "requirements-build.txt"

# Linux x86_64 runtime closure of the custom ILP64 NumPy wheel's MKL dependency,
# installed from PyPI. Resolve against PyPI for the Python 3.12 Debian image when
# bumping MKL. Each hash is the manylinux_2_28_x86_64 wheel's sha256.
MKL_PINS = (
    (
        "mkl==2026.2.1",
        "76322a3abf512594ab7b4e82cb72df91e4e5d195498769aa8b292373c1ddd6d1",
    ),
    (
        "intel-openmp==2026.2.0",
        "2308a1a3e74718a9cd8cccf218c34d8cd80b43d3b89dfbb01b38dee205c50980",
    ),
    (
        "intel-cmplr-lib-ur==2026.2.0",
        "0d0a5099aa2e1e38375b509c2a8182e719ed74aa656b2a800ddf6cfbd3384b80",
    ),
    ("umf==1.2.0", "238d186fdd9e9c0fe1489da95b19b0b79045fe26c4aa98bd0a022a2a3603c195"),
    (
        "tbb==2023.2.0",
        "7d80615b6e970f11671fa05b6eaa9483ac864fbfe525ac280271a78b37870b7c",
    ),
    (
        "tcmlib==1.6.0",
        "46c2491988bfd18c4733eeb08aca6a386706a497b92cc51d155f37ddea003c14",
    ),
)

# Installed from the ILP64 index (https://michael-denyer.github.io/numpy-mkl).
# Each hash is the cp312 manylinux x86_64 wheel's sha256. The numpy version must
# equal the [build-system].requires pin in pyproject.toml, so the extensions
# never build against newer headers than the runtime provides;
# tests/test_dockerfile_provenance.py enforces that equality.
NUMPY_MKL_PINS = (
    (
        "numpy==2.4.6",
        "25e3dcfa3c325950e4802f29ff3cb7c598b4e6fef46591d8f322015e0b9c27c3",
    ),
    (
        "mkl-service==2.8.0",
        "5cdc96f8038f3fd4ed30f39705750244ace0cb800ec761736c4752c2fd08bb43",
    ),
)

# Installed separately from the ILP64 index, so it must not appear here.
EXCLUDED_FROM_LOCK = frozenset({"numpy"})

CONTAINER_HEADER = """\
# Generated by docker/generate-requirements.py. Do not edit by hand.
#
# The runtime pins below the MKL block come from uv.lock, so the image runs the
# same versions the test suite resolves. Regenerate after any lockfile change:
#
#     uv run python docker/generate-requirements.py
#
# JAMMA and the ILP64 NumPy wheel are installed separately (see the Dockerfile)
# so this file can use the default PyPI index safely.
"""

NUMPY_MKL_HEADER = """\
# Generated by docker/generate-requirements.py. Do not edit by hand.
#
# Installed from the ILP64 index, not PyPI (see the Dockerfile). The pins and
# hashes are declared in NUMPY_MKL_PINS in the generator.
"""

BUILD_HEADER = """\
# Generated by docker/generate-requirements.py. Do not edit by hand.
#
# The build backend from the docker-build dependency group in uv.lock, which
# mirrors [build-system].requires without numpy. The Dockerfile installs it and
# builds this checkout without isolation. Regenerate after any lockfile change:
#
#     uv run python docker/generate-requirements.py
"""


def _entry(requirement: str, hashes: list[str]) -> str:
    """Render one requirement with its hashes in pip's continuation-line form."""
    return " \\\n".join([requirement, *(f"    --hash={h}" for h in hashes)])


def _hand_pinned(pins: tuple[tuple[str, str], ...]) -> list[str]:
    return [_entry(pin, [f"sha256:{digest}"]) for pin, digest in pins]


def pins_from_lock(*selection: str) -> list[str]:
    """Return the linux/CPython-3.12 pins and hashes uv.lock records for a selection.

    Args:
        selection: `uv export` options choosing the packages, such as
            `--no-dev` for the runtime closure or `--only-group docker-build`.
    """
    exported = subprocess.run(
        [
            "uv",
            "export",
            *selection,
            "--no-emit-project",
            "--no-annotate",
            "--no-header",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout

    entries = []
    for line in exported.replace("\\\n", " ").splitlines():
        entry = line.strip()
        if not entry or entry.startswith("#"):
            continue
        head, *hashes = (part.strip() for part in entry.split("--hash="))
        requirement, _, marker = head.partition(";")
        if "win32" in marker:
            continue
        requirement = requirement.strip()
        name = re.split(r"[=<>!~\[]", requirement, maxsplit=1)[0]
        if name in EXCLUDED_FROM_LOCK:
            continue
        entries.append(_entry(requirement, hashes))
    return sorted(entries)


def render() -> dict[Path, str]:
    """Return the full text of each generated requirements file."""
    container = [CONTAINER_HEADER, *_hand_pinned(MKL_PINS), *pins_from_lock("--no-dev")]
    numpy_mkl = [NUMPY_MKL_HEADER, *_hand_pinned(NUMPY_MKL_PINS)]
    build = [BUILD_HEADER, *pins_from_lock("--only-group", "docker-build")]
    return {
        CONTAINER_TARGET: "\n".join(container) + "\n",
        NUMPY_MKL_TARGET: "\n".join(numpy_mkl) + "\n",
        BUILD_TARGET: "\n".join(build) + "\n",
    }


def main() -> int:
    rendered = render()
    if "--check" in sys.argv:
        stale = [
            target
            for target, text in rendered.items()
            if (target.read_text() if target.is_file() else "") != text
        ]
        for target in stale:
            print(
                f"{target.relative_to(ROOT)} is stale. "
                "Regenerate with: uv run python docker/generate-requirements.py",
                file=sys.stderr,
            )
        if stale:
            return 1
        print("Container requirements match uv.lock and the declared pins")
        return 0

    for target, text in rendered.items():
        target.write_text(text)
        print(f"Wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
