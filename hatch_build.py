"""Hatchling build hook that embeds the git commit date and compiles the C extensions.

Writes ``src/jamma/_build_meta.py`` at build time so the release date is
available at runtime via ``jamma.__release_date__`` without manual upkeep.

Also compiles two C extensions if a C compiler is available:
  - ``src/jamma/lmm/_lmm_accel.c``: per-SNP REML Wald pipeline (with OpenMP)
  - ``src/jamma/jlinalg/src/*.c``: jlinalg BLAS compute layer (with OpenMP)

If compilation fails for any reason, a warning is logged and a pure-Python
wheel is produced as a graceful fallback — jamma is fully functional without
either C extension.
"""

import datetime
import os
import platform
import shutil
import subprocess
import sys
import sysconfig
import tempfile
from pathlib import Path

# hatch_build.py is the PEP 517 build backend — runs before jamma is
# installed, so it cannot `from jamma.* import ...`. build_support/ sits
# at repo root as a sibling to src/; insert repo root on sys.path so we
# can import the shared compile helpers. Convention: numpy / scipy /
# pyarrow all use this pattern for PEP 517 build helpers.
sys.path.insert(0, str(Path(__file__).parent))

from build_support.compile_and_link import (  # noqa: E402
    BASE_CFLAGS,
    BASELINE_SOURCES,
    LAPACK_CFLAGS,
    LAPACK_SOURCES,
    LINK_FLAGS_BY_PLATFORM,
    compile_jlinalg,
    resolve_cflags_for,
)
from build_support.find_compiler import find_c_compiler  # noqa: E402
from build_support.openmp_detect import detect_openmp_flags  # noqa: E402

from hatchling.builders.hooks.plugin.interface import BuildHookInterface  # noqa: E402


class CustomBuildHook(BuildHookInterface):
    def initialize(self, version, build_data):
        # Write _build_meta.py with the git commit date
        try:
            date_str = subprocess.check_output(
                ["git", "log", "-1", "--format=%ci"],
                text=True,
                stderr=subprocess.DEVNULL,
            ).strip()[:10]
        except (FileNotFoundError, subprocess.CalledProcessError):
            date_str = datetime.date.today().isoformat()

        meta_path = Path(self.root) / "src" / "jamma" / "_build_meta.py"
        meta_path.write_text(
            f'"""Auto-generated by hatch_build.py - do not edit."""\n\n'
            f'BUILD_DATE = "{date_str}"\n'
        )

        # Compile C extensions (graceful fallback if unavailable).
        # _lmm_accel is more critical — compile first so its errors are visible.
        self._compile_c_extension(build_data)
        self._compile_jlinalg_extension(build_data)

    def _preflight_c_build(self):
        """Verify build prerequisites and return compiler/include information.

        Checks that numpy >= 2.0 is available, the C compiler is on PATH,
        and Python.h exists. All checks produce actionable WARNING messages
        on failure.

        Returns:
            tuple(cc_cmd, cc_extra, python_inc, numpy_inc, ldflags) on success,
            or None if any pre-flight check fails.
        """
        try:
            import numpy as np
        except ImportError:
            print(
                "WARNING: numpy not available in build environment — "
                "skipping C extension compilation (pure-Python fallback).",
                file=sys.stderr,
            )
            return None

        # Refuse to compile against numpy 1.x — the resulting .so crashes on
        # numpy 2.x at import time due to C API ABI break (NPY_ABI_VERSION).
        np_major = int(np.__version__.split(".")[0])
        if np_major < 2:
            print(
                f"WARNING: build numpy is {np.__version__} (1.x) — "
                "skipping C extension to avoid ABI mismatch with numpy 2.x "
                "at runtime (pure-Python fallback).\n"
                "  To compile the C extension, build with numpy >= 2.0:\n"
                "    pip install --no-build-isolation --no-deps jamma",
                file=sys.stderr,
            )
            return None

        # Compiler discovery delegated to build_support.find_compiler.
        # Honours $CC, falls back to sysconfig + cc/clang/gcc with probing.
        cc_env = os.environ.get("CC")
        if cc_env is not None and not cc_env.strip():
            print(
                "WARNING: CC is set but empty — "
                "skipping C extension compilation (pure-Python fallback).",
                file=sys.stderr,
            )
            return None

        compiler = find_c_compiler()
        if compiler is None:
            if cc_env:
                print(
                    f"WARNING: $CC is set to '{cc_env}' but compiler "
                    "verification failed — skipping C extension "
                    "compilation (pure-Python fallback).",
                    file=sys.stderr,
                )
            else:
                print(
                    "WARNING: no usable C compiler found — "
                    "skipping C extension compilation (pure-Python fallback).\n"
                    "  To enable the C extension, install a C compiler:\n"
                    "    Debian/Ubuntu: apt-get install -y gcc\n"
                    "    macOS: xcode-select --install",
                    file=sys.stderr,
                )
            return None
        cc_cmd, cc_extra = compiler

        python_inc = sysconfig.get_config_var("INCLUDEPY")
        numpy_inc = np.get_include()

        # Pre-flight: verify Python.h exists (python3-dev package)
        python_h = Path(python_inc) / "Python.h" if python_inc else None
        if not python_h or not python_h.exists():
            print(
                f"WARNING: Python.h not found at {python_inc} — "
                "skipping C extension compilation (pure-Python fallback).\n"
                "  To enable the C extension, install Python development headers:\n"
                "    Debian/Ubuntu: apt-get install -y python3-dev\n"
                "    Fedora/RHEL: dnf install python3-devel",
                file=sys.stderr,
            )
            return None

        # macOS requires -undefined dynamic_lookup for Python C extensions
        # (Python symbols are resolved at runtime from the embedding binary)
        ldflags = []
        if platform.system() == "Darwin":
            ldflags = ["-undefined", "dynamic_lookup"]

        return (cc_cmd, cc_extra, python_inc, numpy_inc, ldflags)

    def _compile_c_extension(self, build_data):
        """Compile _lmm_accel.c -> _lmm_accel{EXT_SUFFIX} if a C compiler is available.

        Uses sysconfig to locate Python headers and numpy to locate its include
        directory. OpenMP support is detected via build_support.openmp_detect
        (handles Linux and Darwin uniformly).

        On any compilation failure, logs a warning and returns without raising.
        The compiled .so is written to src/jamma/lmm/ where hatchling's normal
        package discovery picks it up automatically for wheel inclusion.

        Args:
            build_data: Hatchling build data dict. Updated with force_include
                entry mapping the compiled .so into the wheel.
        """
        preflight = self._preflight_c_build()
        if preflight is None:
            return
        cc_cmd, cc_extra, python_inc, numpy_inc, ldflags = preflight

        src = Path(self.root) / "src" / "jamma" / "lmm" / "_lmm_accel.c"
        if not src.exists():
            print(
                f"WARNING: C source {src} not found — skipping C extension "
                "compilation (pure-Python fallback). If building from sdist, "
                "verify the archive is complete.",
                file=sys.stderr,
            )
            return

        ext_suffix = sysconfig.get_config_var("EXT_SUFFIX") or ".so"
        out_name = f"_lmm_accel{ext_suffix}"
        out_path = Path(self.root) / "src" / "jamma" / "lmm" / out_name

        # Unified OpenMP detection — handles prefer-clang for libiomp5 on
        # Linux, Homebrew on Darwin, and the JAMMA_NO_OPENMP escape hatch.
        omp_compile, omp_link, cc_cmd = detect_openmp_flags(
            cc_cmd,
            platform.system(),
            _print=lambda *a, **kw: print(*a, **{"file": sys.stderr, **kw}),
            _warn=lambda *a, **kw: print(*a, **{"file": sys.stderr, **kw}),
        )

        # Respect CFLAGS for arch-specific builds (e.g. -march=x86-64-v3)
        extra_cflags = os.environ.get("CFLAGS", "").split()

        # Two-step compile+link to prevent dual OpenMP runtime.
        # GCC's -fopenmp implicitly adds -lgomp at link time. When Intel's
        # OMP runtime (bundled with MKL numpy) is also linked, both runtimes
        # initialize and abort: "OMP: Error #13: Assertion failure at
        # kmp_runtime.cpp". Splitting into compile (.o) then link (.so) lets
        # us pass -fopenmp only to the compiler and link only the runtime.
        obj_path = out_path.with_suffix(".o")

        compile_cmd = [
            cc_cmd,
            *cc_extra,
            "-O3",
            "-ftree-vectorize",
            "-fno-math-errno",
            "-fno-trapping-math",
            "-funroll-loops",
            *extra_cflags,
            "-fno-finite-math-only",  # override -Ofast in CFLAGS; isnan() must work
            "-Wframe-larger-than=131072",
            "-fPIC",
            "-std=c11",
            f"-I{python_inc}",
            f"-I{numpy_inc}",
            *omp_compile,
            "-c",
            str(src),
            "-o",
            str(obj_path),
        ]

        result = subprocess.run(compile_cmd, capture_output=True, text=True)
        if result.returncode != 0:
            if omp_compile:
                # Retry without OpenMP — libgomp may not be installed
                compile_cmd_no_omp = [x for x in compile_cmd if x not in omp_compile]
                print(
                    "OpenMP compilation failed, retrying without OpenMP "
                    "(single-threaded C extension)...",
                    file=sys.stderr,
                )
                result2 = subprocess.run(
                    compile_cmd_no_omp, capture_output=True, text=True
                )
                if result2.returncode == 0:
                    omp_link = []  # Don't link OpenMP if compile failed
                else:
                    print(
                        "WARNING: C extension compilation failed "
                        "(pure-Python fallback will be used):\n"
                        f"  OpenMP error: {result.stderr[:1000]}\n"
                        f"  No-OpenMP error: {result2.stderr[:1000]}",
                        file=sys.stderr,
                    )
                    obj_path.unlink(missing_ok=True)
                    return
            else:
                print(
                    "WARNING: C extension compilation failed "
                    "(pure-Python fallback will be used):\n"
                    f"  Command: {' '.join(compile_cmd)}\n"
                    f"  Error: {result.stderr[:2000]}",
                    file=sys.stderr,
                )
                return

        # Link step: .o -> .so (no -fopenmp here — only runtime link flags)
        link_cmd = [
            cc_cmd,
            "-shared",
            str(obj_path),
            "-o",
            str(out_path),
            *omp_link,
            "-lm",
            *ldflags,
        ]

        result = subprocess.run(link_cmd, capture_output=True, text=True)
        obj_path.unlink(missing_ok=True)  # Clean up .o regardless
        if result.returncode != 0:
            print(
                "WARNING: C extension link failed "
                "(pure-Python fallback will be used):\n"
                f"  Command: {' '.join(link_cmd)}\n"
                f"  Error: {result.stderr[:2000]}",
                file=sys.stderr,
            )
            return

        print(f"C extension compiled: {out_path}", file=sys.stderr)

        # Register the compiled .so as a forced wheel inclusion.
        # force_include maps: absolute_source_path -> distribution_path
        # distribution_path is relative to the package root within the wheel,
        # e.g. "jamma/lmm/_lmm_accel.cpython-311-darwin.so"
        build_data.setdefault("force_include", {})
        dist_path = f"jamma/lmm/{out_name}"
        build_data["force_include"][str(out_path)] = dist_path

        # Tell hatchling this is a platform wheel (not pure-Python).
        # Without this, the wheel gets tagged py3-none-any even though it
        # contains a compiled .so, and cibuildwheel rejects it.
        # infer_tag makes hatchling use the current platform/ABI for the
        # wheel filename tag (e.g. cp311-cp311-macosx_14_0_arm64).
        build_data["pure_python"] = False
        build_data["infer_tag"] = True

    def _compile_jlinalg_extension(self, build_data):
        """Compile jlinalg C sources -> _jlinalg{EXT_SUFFIX}.

        Per-file compile-then-link.

        Compiles each C source file in src/jamma/jlinalg/src/ individually to a
        temporary object file, then links them into a single shared library.
        This enables per-file compiler flag groups (e.g. AVX2 files vs LAPACK files
        with distinct flag sets in future phases).

        OpenMP support is detected via build_support.openmp_detect
        (handles Linux and Darwin uniformly).

        On any compilation failure, logs a warning and returns without raising.
        The compiled .so is written to src/jamma/jlinalg/.

        Args:
            build_data: Hatchling build data dict. Updated with force_include
                entry mapping the compiled .so into the wheel.
        """
        preflight = self._preflight_c_build()
        if preflight is None:
            return
        cc_cmd, cc_extra, python_inc, numpy_inc, ldflags = preflight

        jlinalg_src = Path(self.root) / "src" / "jamma" / "jlinalg" / "src"
        jlinalg_inc = Path(self.root) / "src" / "jamma" / "jlinalg" / "include"

        if not jlinalg_src.is_dir():
            print(
                f"WARNING: jlinalg source directory {jlinalg_src} not found — "
                "skipping jlinalg C extension compilation (NumPy fallback).",
                file=sys.stderr,
            )
            return

        # jlinalg source files split into two groups:
        # - baseline: portable C compiled with standard flags
        # - lapack: eigh.c compiled with strict IEEE 754 flags
        baseline_sources = [
            jlinalg_src / "platform.c",
            jlinalg_src / "pymodule.c",
            jlinalg_src / "blas_dispatch.c",
            jlinalg_src / "snp_stats.c",
        ]
        # LAPACK sources: strict IEEE 754 required for vendor LAPACK dispatch.
        # Compiled with -O2 only — MUST NOT get -ffast-math, -Ofast,
        # -ffinite-math-only, or -funroll-loops.
        lapack_sources = [
            jlinalg_src / "eigh.c",
        ]

        source_files = baseline_sources + lapack_sources

        missing = [s for s in source_files if not s.exists()]
        if missing:
            print(
                f"WARNING: jlinalg source files missing: {missing} — "
                "skipping jlinalg C extension compilation (NumPy fallback).",
                file=sys.stderr,
            )
            return

        # Unified OpenMP detection — same helper the _lmm_accel path uses.
        omp_compile, omp_link, cc_cmd = detect_openmp_flags(
            cc_cmd,
            platform.system(),
            _print=lambda *a, **kw: print(*a, **{"file": sys.stderr, **kw}),
            _warn=lambda *a, **kw: print(*a, **{"file": sys.stderr, **kw}),
        )

        # Respect CFLAGS for arch-specific builds (e.g. -march=x86-64-v3)
        extra_cflags = os.environ.get("CFLAGS", "").split()

        # Base compile flags shared by all source files (no SIMD flags here)
        base_cflags = [
            "-O3",
            "-ftree-vectorize",
            "-fno-math-errno",
            "-fno-trapping-math",
            "-funroll-loops",
            *extra_cflags,
            "-fno-finite-math-only",  # override -Ofast; isnan() must work
            "-Wframe-larger-than=131072",
            "-fPIC",
            "-std=c11",
            f"-I{python_inc}",
            f"-I{numpy_inc}",
            f"-I{jlinalg_inc}",
        ]

        ext_suffix = sysconfig.get_config_var("EXT_SUFFIX") or ".so"
        out_name = f"_jlinalg{ext_suffix}"
        out_path = Path(self.root) / "src" / "jamma" / "jlinalg" / out_name

        # Compile each source file to a .o in a temporary directory
        tmp_dir = Path(tempfile.mkdtemp(prefix="jlinalg_build_"))
        obj_files: list[Path] = []
        compile_failed = False
        use_omp = bool(omp_compile)

        lapack_source_set = {str(s) for s in lapack_sources}

        # Strict IEEE 754 flags for LAPACK sources (secular equation deflation
        # uses infinity arithmetic that -ffast-math breaks).
        lapack_cflags = [
            "-O2",
            "-fno-fast-math",
            "-fno-finite-math-only",
            "-Wframe-larger-than=131072",
            "-fPIC",
            "-std=c11",
            f"-I{python_inc}",
            f"-I{numpy_inc}",
            f"-I{jlinalg_inc}",
        ]

        def _jlinalg_compile_cmd(
            src: Path,
            obj_file: Path,
            omp_compile_flags: list[str],
        ) -> list[str]:
            """Build the compile command for a single jlinalg source file.

            LAPACK sources get strict IEEE 754 flags (no -ffast-math).
            Baseline sources get standard optimization flags.

            Args:
                src: Source file path.
                obj_file: Output object file path.
                omp_compile_flags: OpenMP compile-only flags (empty to disable).

            Returns:
                Compiler command as a list of strings.
            """
            cflags = lapack_cflags if str(src) in lapack_source_set else base_cflags
            return [
                cc_cmd,
                *cc_extra,
                *cflags,
                *omp_compile_flags,
                "-c",
                str(src),
                "-o",
                str(obj_file),
            ]

        try:
            for src in source_files:
                obj_file = tmp_dir / (src.stem + ".o")
                cmd_compile = _jlinalg_compile_cmd(src, obj_file, omp_compile)
                # Print compile command to stderr for build-log assertions (CI grep)
                print(f"jlinalg compile: {' '.join(cmd_compile)}", file=sys.stderr)
                result = subprocess.run(cmd_compile, capture_output=True, text=True)
                if result.returncode != 0:
                    print(
                        f"jlinalg compile failed on {src.name}:",
                        file=sys.stderr,
                    )
                    if result.stderr:
                        print(result.stderr, file=sys.stderr)
                    compile_failed = True
                    break
                obj_files.append(obj_file)

            if compile_failed and use_omp:
                # Retry without OpenMP compile flags
                print(
                    "jlinalg OpenMP compilation failed, retrying without OpenMP...",
                    file=sys.stderr,
                )
                obj_files.clear()
                compile_failed = False
                for src in source_files:
                    obj_file = tmp_dir / (src.stem + "_noomp.o")
                    cmd_compile = _jlinalg_compile_cmd(src, obj_file, [])
                    print(
                        f"jlinalg compile (no OMP): {' '.join(cmd_compile)}",
                        file=sys.stderr,
                    )
                    result = subprocess.run(cmd_compile, capture_output=True, text=True)
                    if result.returncode != 0:
                        print(
                            "WARNING: jlinalg C extension compilation failed on "
                            f"{src.name} (NumPy fallback will be used):\n"
                            f"  Error: {result.stderr[:1000]}",
                            file=sys.stderr,
                        )
                        compile_failed = True
                        break
                    obj_files.append(obj_file)
                # No OMP runtime to link if compile retry dropped OMP flags
                omp_link = []

            if compile_failed:
                print(
                    "WARNING: jlinalg C extension compilation failed "
                    "(NumPy fallback will be used).",
                    file=sys.stderr,
                )
                return

            # dlopen/dlsym in blas_dispatch.c needs -ldl on Linux
            # -ldl for dlopen/dlsym in blas_dispatch.c
            # -lpthread for snp_stats.c (uses pthreads directly, not OpenMP)
            dl_flags = ["-ldl", "-lpthread"] if platform.system() == "Linux" else []

            # Link all object files into the shared library
            cmd_link = [
                cc_cmd,
                *cc_extra,
                "-shared",
                "-fPIC",
                *[str(o) for o in obj_files],
                "-o",
                str(out_path),
                "-lm",
                *dl_flags,
                *omp_link,
                *ldflags,
            ]
            print(f"jlinalg link: {' '.join(cmd_link)}", file=sys.stderr)
            result_link = subprocess.run(cmd_link, capture_output=True, text=True)
            if result_link.returncode != 0:
                print(
                    "WARNING: jlinalg C extension link failed "
                    "(NumPy fallback will be used):\n"
                    f"  Command: {' '.join(cmd_link)}\n"
                    f"  Error: {result_link.stderr[:2000]}",
                    file=sys.stderr,
                )
                return

        finally:
            # Clean up temporary object files
            shutil.rmtree(tmp_dir, ignore_errors=True)

        print(f"jlinalg C extension compiled: {out_path}", file=sys.stderr)

        # Register the compiled .so for wheel inclusion
        build_data.setdefault("force_include", {})
        build_data["force_include"][str(out_path)] = f"jamma/jlinalg/{out_name}"
        build_data["pure_python"] = False
        build_data["infer_tag"] = True
